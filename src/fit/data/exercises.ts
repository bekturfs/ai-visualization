/** Фотографии стартовой и конечной позиции: открытая база free-exercise-db (CC0). */
export const PHOTO_BASE =
  "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/";

export function photoUrls(folder?: string): [string, string] | null {
  if (!folder) return null;
  return [`${PHOTO_BASE}${folder}/0.jpg`, `${PHOTO_BASE}${folder}/1.jpg`];
}

/** Ссылка на поиск техники в YouTube — работает всегда, ничего не выдумываем. */
export function videoSearchUrl(ex: { name: string; en: string }): string {
  return (
    "https://www.youtube.com/results?search_query=" +
    encodeURIComponent(`${ex.en} техника ${ex.name}`)
  );
}

